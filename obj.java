

public class obj {
    String name;
    int cod_vendedor;
    String fecha;
    double valor;
    
    public obj(String name, int cod_vendedor, String fecha, double valor) {
        this.name = name;
        this.cod_vendedor = cod_vendedor;
        this.fecha = fecha;
        this.valor = valor;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getCod_vendedor() {
        return cod_vendedor;
    }

    public void setCod_vendedor(int cod_vendedor) {
        this.cod_vendedor = cod_vendedor;
    }

    public String getFecha() {
        return fecha;
    }

    public void setFecha(String fecha) {
        this.fecha = fecha;
    }

    public double getValor() {
        return valor;
    }

    public void setValor(double valor) {
        this.valor = valor;
    }

    
   
    

    
    
}
